DECLARE @OnMachine TABLE (id BIGINT PRIMARY KEY, JobCardContentNo NVARCHAR(100), curPos INT);
INSERT INTO @OnMachine (id, JobCardContentNo, curPos)
SELECT w.JobBookingJobcardContentsID, MAX(w.JobCardContentNo), ROW_NUMBER() OVER (ORDER BY MIN(w.StartTime))
FROM dbo.JobScheduleReleaseMachineWise w
WHERE w.MachineID = @MachineID
GROUP BY w.JobBookingJobcardContentsID;

DECLARE @Ordered TABLE (id BIGINT, pos INT);
INSERT INTO @Ordered (id, pos)
SELECT m.id, ROW_NUMBER() OVER (ORDER BY CASE WHEN p.pos IS NULL THEN 1 ELSE 0 END, p.pos, m.curPos)
FROM @OnMachine m
LEFT JOIN @Plan p ON p.JobCardContentNo = m.JobCardContentNo;

-- 1) Preview: new position, job card, and where it came from
SELECT o.pos, m.JobCardContentNo, CASE WHEN p.pos IS NULL THEN 'new since 10 Nov' ELSE 'plan #' + CAST(p.pos AS VARCHAR) END AS source
FROM @Ordered o JOIN @OnMachine m ON m.id = o.id LEFT JOIN @Plan p ON p.JobCardContentNo = m.JobCardContentNo
ORDER BY o.pos;

